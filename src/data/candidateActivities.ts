export const SUPPORTED_DESTINATIONS = ['Pune', 'Goa', 'Jaipur', 'Bengaluru', 'Mumbai'] as const;

export function normalizeDestination(dest: string): string {
  const clean = dest.trim().toLowerCase();
  if (clean.includes('pune')) return 'Pune';
  if (clean.includes('goa')) return 'Goa';
  if (clean.includes('jaipur')) return 'Jaipur';
  if (clean.includes('bengaluru') || clean.includes('bangalore')) return 'Bengaluru';
  if (clean.includes('mumbai') || clean.includes('bombay')) return 'Mumbai';
  return dest.trim();
}

export function isDestinationSupported(dest: string): boolean {
  const normalized = normalizeDestination(dest);
  return SUPPORTED_DESTINATIONS.includes(normalized as (typeof SUPPORTED_DESTINATIONS)[number]);
}

